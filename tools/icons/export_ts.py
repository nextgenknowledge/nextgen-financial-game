"""Writes src/ui/icons/pixelIcons.ts: the icon grids as data, for drawing on canvases (maps)."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from designs import D, PALETTE  # noqa: E402

NAMES = ['bank', 'cash', 'coin', 'bags', 'shop', 'bowl', 'coffee', 'book', 'books', 'star', 'question', 'plane', 'paw', 'car', 'chart_up',
         'house', 'portal', 'seedling', 'shield', 'briefcase', 'gamepad', 'palette', 'office', 'school', 'masks', 'mic', 'newspaper',
         'computer', 'robot', 'exchange', 'scales', 'heart', 'medical', 'lantern', 'package', 'truck', 'shirt', 'map', 'trophy',
         'calendar', 'receipt', 'piggy', 'key', 'flower', 'tree', 'globe', 'card', 'factory', 'construction', 'pin']

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', '..', 'src', 'ui', 'icons', 'pixelIcons.ts')
os.makedirs(os.path.dirname(out), exist_ok=True)
grids = {n: [''.join(r) for r in D[n]()] for n in NAMES}
with open(out, 'w') as f:
    f.write('/* Generated by tools/icons/export_ts.py from tools/icons/designs.py. Do not edit by hand. */\n')
    f.write('export const ICON_PALETTE: Record<string, string> = ' + json.dumps(PALETTE) + ';\n\n')
    f.write('export const ICONS = ' + json.dumps(grids, indent=1) + ' as const;\n\n')
    f.write('export type IconName = keyof typeof ICONS;\n\n')
    f.write('''/** Draws a 16x16 pixel icon with its top-left at (x, y), `px` canvas pixels per icon pixel. */
export function drawIcon(g: CanvasRenderingContext2D, name: IconName, x: number, y: number, px = 1) {
  const rows = ICONS[name];
  for (let j = 0; j < 16; j++)
    for (let i = 0; i < 16; i++) {
      const ch = rows[j][i];
      if (ch === '.') continue;
      g.fillStyle = ICON_PALETTE[ch];
      g.fillRect(Math.round(x + i * px), Math.round(y + j * px), Math.ceil(px), Math.ceil(px));
    }
}
''')
print('wrote', os.path.normpath(out))
